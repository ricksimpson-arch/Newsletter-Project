interface CompactSeedInput {
  rank: number;
  name: string;
  slug: string;
  ownership: OwnershipType;
  audience: AudienceType;
  score: number;
  criteria: CriterionScores;
  read: string;
  summary: string;
  opportunity: string;
  risk: string;
  best: string[];
  themes: string[];
  whitespace: string[];
  licensingComplexity: number;
  landscape?: string[];
  licensingNotes?: string[];
  confidence?: ConfidenceComponents;
  sourceIds?: string[];
  lastVerifiedAt?: string;
  catalystIds?: string[];
}

function compact(input: CompactSeedInput): FranchiseSeed {
  const sonyish = input.ownership !== "non-sony";
  return {
    rank: input.rank,
    name: input.name,
    slug: input.slug,
    ownershipType: input.ownership,
    audienceType: input.audience,
    seedScore: input.score,
    criterionScores: input.criteria,
    criterionProvenance: "modeled",
    commercialRead: input.read,
    executiveSummary: input.summary,
    mainOpportunity: input.opportunity,
    mainRisk: input.risk,
    bestCategories: input.best,
    targetDemographics: DEMOGRAPHIC_DEFAULTS[input.audience],
    licensingComplexity: input.licensingComplexity,
    licensingNotes: input.licensingNotes ?? LICENSING_DEFAULTS[input.ownership],
    competitiveLandscape: input.landscape ?? [
      "Limited official merchandise presence; competition comes mostly from generic aesthetic lookalikes.",
    ],
    whitespaceOpportunities: input.whitespace,
    visualThemes: input.themes,
    hasPublicSalesData: false,
    confidenceComponents:
      input.confidence ??
      (input.ownership === "legacy"
        ? CONFIDENCE_PRESETS.legacy
        : sonyish
          ? CONFIDENCE_PRESETS.modernSony
          : CONFIDENCE_PRESETS.thirdParty),
    catalystIds: input.catalystIds ?? [],
    sourceIds:
      input.sourceIds ??
      (sonyish
        ? ["sie-timeline", "ps-licensing-program", "lootsignal-internal-model"]
        : ["lootsignal-internal-model"]),
    lastVerifiedAt:
      input.lastVerifiedAt ?? (input.ownership === "legacy" ? "2025-11-20" : "2026-06-24"),
  };
}

